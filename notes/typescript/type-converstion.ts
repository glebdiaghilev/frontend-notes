/*
преобразование типов подразумевает, когда мы один 
тип явно или неявно превращаем в другой.

преобразование типов бывает:
1. явным;
2. неявным.

есть явный и неявный вывод типов, но преобразование
типов - это немного другое.

с неявным преобразованием все просто - прибавили число 
к строке и число стало строкой, конкатенация.

явное преобразование. представим, у нас есть объект,
для ts это просто объект с 2 полями. мы его явно определили
в коде, и проблем нет. Но если мы получили этот же объект
с сервера? ts его уже не прочитает, для него это obj
с какими-то полями, который вывести он не сможет.

для решения подобных проблем есть as. допустим мы распарсили
представленный person, и мы хотим сказать, что obj - person.
этот метод небезопасен и в реальном продакшене его следует
избегать.

мы добавили еще одно обязательное поле, password, но в obj
поле не указано, ошибки от ts не будет, так как мы уже
преобразовали obj в person, он думает, что это поле уже есть.

в этом методе есть множество странных вещей, например, в obj
мы добавили несуществующее поле shit, и если мы после него
все-таки укажем поле password, то ошибки не будет.

можно указать person перед объектом <person> - это не generic,
и он не воспринимается jsx.

ts все-таки не дает сделать глупое явное преобразование типов.
есть метод, чтобы это обойти, но в продакшене так делать нельзя.

есть особый метод satisfies, в отличие от as оно не преобразовывает
объект, оно лишь проверяет соответствие. прежний объект останется
таким же и в person не превратиться, но ts проверит совпадают ли
эти объекты структурно.

понятно, что as в продакшене лучше не использовать, так как это
any в другой обертке

допустимо использовать as:
1. в конфигах;
2. в тестах;
3. при работе с html элементами (иногда);
4. в утилитарных функциях;
5. когда ts не может вывести тип.

просто так преобразовать один тип в другой нельзя!
лучше настроить линтер, чтобы один тип в другой 
не преобразовывать.

есть одна очень важная ловушка, которую допускают много людей.
это ловушка: <T extends Object>, есть здесь один нюанс.
*/
