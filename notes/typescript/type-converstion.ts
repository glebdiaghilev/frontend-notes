// явное преобразование
interface Person {
    age: number
    username: string

    // добавим еще одно поле
    password: string
}

// небезопасный метод as
const obj = {
    age: 25,
    username: 'gleb',
    shit: 123,
    password: 'svg'
} as Person

// метод лучше, но не воспринимается jsx
const obj2 = <Person>{
	age: 25,
	username: 'gleb'
}

// глупые явные преобразования ts сделать не даст:
