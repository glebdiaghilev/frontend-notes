/*
элементы в массиве могут быть любым типом данных. 
обычно в массиве хранят данные одного типа, например,
только строки, только числа, только объекты.
формально можно и поместить элементы разных типов
*/

const arrayIsObject = [
	'hello',
	100,
	true,
]

// массив - это объект.
// в терминале мы увидим объект с именами 0, 1, 2
console.log("arr:", arrayIsObject)

// доказательство того, что массив - это объект.
console.log("typeof arr:", typeof arrayIsObject)

// получение элемента массива по его индексу.
const getArray = [
	'hello',
	100,
	true,

	// добавим еще три элемента
	{ name: 'gleb' },
	() => console.log('huh'),
	[true, true, true],
]

// как мы видим в терминале, каждый элемент имеет свой индекс.
console.log(getArray[0])

// если мы объявим индекс, которого нет, то будет undefined
console.log(getArray[999])

