// изменение элемента массива 
const changeArray = [
    "hello",
    100,
    true,
]

console.log( "arr before:", changeArray )

// присваиваем другие значения. формально мы массив не меняем, переопределяем значения
changeArray[0] = "bye!"
changeArray[1] = 200
changeArray[2] = false

// присваиваем значение несуществующему элементу. мы создали новый элемент 
changeArray[3] = '100'

// значение по большому индексу. теперь у нас 101 элемент. 96 элементов empty и в конце 'wow!'
changeArray[100] = 'wow!'

// в терминале есть свойство length для длины массива, оно появляется всегда
console.log( "arr after:", changeArray )

// чтобы узнать длину массива пишем length
console.log( "length arr:", changeArray )

/*
массив - это почти всегда динамическая коллекция данных, 
иначе говоря, мы не всегда знаем какой длины будет массив.
*/

// с помощью length можно получить последний элемент массива
// последний элемент массива почти всегда имеет индекс меньше, чем length массива
console.log( changeArray[changeArray.length - 1] )

// для этого есть встроенные оператор at. сработает как обращение по индексу
console.log( changeArray.at(-1) )

// часто приходится работать с массивами как с очередью
const letters = ['A', 'B', 'C']

console.log( 'letters before:', letters )

// используем push, чтобы добавить элементы в конец массива
letters.push('D')

// используем unshift, чтобы добавить элементы в начало массива
// все предыдущие элементы сдвинулись на одну позицию. индексы увеличились
letters.unshift("-A")
// операция unshift неоптимальная. удалять/прибавлять элементы из начала дорого!!!

// удаление элемента с конца массива.
letters.pop()

// метод pop() не только удаляет но и возвращает элемент
console.log( letters.pop() )

// удаление элемента с начала массива
letters.shift()
// так же как и с unshift эта операция неоптимальная

console.log( 'letters after:', letters )

