/*
 массив в js - это не отдельный тип данных! 
 Это специальная структура, коллекция, 
 в котором элементы хранятся в том порядке, 
 в котором их поместили в массив.
*/

// простой способ создать массив, самый популярный
const celebrityArray = []

// есть еще способ, но такой способ используют редко
